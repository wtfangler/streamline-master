"""Installs a built pack into a fresh game directory and starts the real client on it.

    python ci/run_client.py <pack.mrpack> --dev <dir from fetch_dev.py> --game <dir> --out <results dir>

Every mod is downloaded from the URL in the pack and checked against its SHA-512,
exactly as a launcher would. A world is generated by the vanilla dedicated server,
the CI harness mod is added, and the client joins that world, takes screenshots
and quits. Writes <out>/summary.md, <out>/client.log and the screenshots.
Meant for CI under Xvfb with Mesa's software renderer: it proves the pack starts
and shows what the screens look like; its frame rate means nothing.
"""
import argparse
import glob
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.request
import uuid
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from tune import G1_ARGS  # noqa: E402  the pack's own recommended JVM arguments

WORLD = "Test"
NOISE = re.compile(r"(\bERROR\b|Exception|Mixin apply failed|Could not|Failed to|Incompatible mod)")


def log(text):
    print(text, flush=True)


def download(url, sha512, cache):
    path = os.path.join(cache, sha512)
    if not os.path.isfile(path):
        req = urllib.request.Request(url, headers={"User-Agent": "streamline-master-ci"})
        with urllib.request.urlopen(req, timeout=120) as r:
            data = r.read()
        if hashlib.sha512(data).hexdigest() != sha512:
            raise RuntimeError("sha512 mismatch: %s" % url)
        with open(path, "wb") as f:
            f.write(data)
    return path


def install_pack(pack, game, cache):
    os.makedirs(cache, exist_ok=True)
    with zipfile.ZipFile(pack) as z:
        idx = json.loads(z.read("modrinth.index.json"))
        for f in idx["files"]:
            if f["env"]["client"] == "unsupported":
                continue
            target = os.path.join(game, f["path"])
            os.makedirs(os.path.dirname(target), exist_ok=True)
            shutil.copyfile(download(f["downloads"][0], f["hashes"]["sha512"], cache), target)
        for n in z.namelist():
            if n.startswith("overrides/") and not n.endswith("/"):
                target = os.path.join(game, n[len("overrides/"):])
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(target, "wb") as out:
                    out.write(z.read(n))
    log("installed %d indexed files and the overrides of %s" % (len(idx["files"]), idx["versionId"]))
    return idx


def build_harness(dev, mc, game):
    tmp = os.path.join(game, ".harness-build")
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)
    cp = [os.path.join(dev, mc, "client.jar")] + sorted(glob.glob(os.path.join(dev, mc, "libs", "*.jar"))) \
        + sorted(glob.glob(os.path.join(dev, "fabric", "*.jar")))
    src = sorted(glob.glob(os.path.join(HERE, "harness", "src", "**", "*.java"), recursive=True))
    subprocess.run(["javac", "--release", "25", "-proc:none", "-d", tmp, "-cp", os.pathsep.join(cp)] + src, check=True)
    with zipfile.ZipFile(os.path.join(game, "mods", "slm_harness.jar"), "w", zipfile.ZIP_DEFLATED) as z:
        for base in (tmp, os.path.join(HERE, "harness", "resources")):
            for dirpath, _, names in os.walk(base):
                for n in names:
                    full = os.path.join(dirpath, n)
                    z.write(full, os.path.relpath(full, base).replace(os.sep, "/"))
    shutil.rmtree(tmp)


def generate_world(dev, mc, game, work):
    """The dedicated server writes a world singleplayer can open, without any client-side world-creation API."""
    server = os.path.join(work, "server")
    shutil.rmtree(server, ignore_errors=True)
    os.makedirs(server)
    with open(os.path.join(server, "eula.txt"), "w") as f:
        f.write("eula=true\n")
    with open(os.path.join(server, "server.properties"), "w") as f:
        f.write("level-name=%s\nlevel-seed=streamline\nonline-mode=false\nview-distance=6\nspawn-protection=0\n" % WORLD)
    proc = subprocess.Popen(["java", "-Xmx2G", "-jar", os.path.join(dev, mc, "server.jar"), "nogui"], cwd=server,
                            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    start = time.time()
    for line in proc.stdout:
        if "Done (" in line:
            proc.stdin.write("stop\n")
            proc.stdin.flush()
        if time.time() - start > 600:
            proc.kill()
            raise RuntimeError("world generation timed out")
    proc.wait(timeout=120)
    shutil.copytree(os.path.join(server, WORLD), os.path.join(game, "saves", WORLD))
    log("world generated in %.0f s" % (time.time() - start))


def allowed(rules):
    if not rules:
        return True
    ok = False
    for rule in rules:
        if "features" in rule:
            continue
        osr = rule.get("os")
        if not osr or osr.get("name") == "linux":
            ok = rule["action"] == "allow"
    return ok


def lib_key(name):
    parts = name.split(":")
    return ":".join(parts[:2] + parts[3:])


def launch(dev, mc, game, timeout):
    vj = json.load(open(os.path.join(dev, mc, "version.json")))
    profile = json.load(open(os.path.join(dev, "fabric", "profile.json")))
    libs = {}
    for lib in vj["libraries"]:
        art = (lib.get("downloads") or {}).get("artifact")
        if art and allowed(lib.get("rules")):
            libs[lib_key(lib["name"])] = os.path.join(dev, mc, "libs", os.path.basename(art["path"]))
    for lib in profile["libraries"]:
        parts = lib["name"].split(":")
        jar = "%s-%s%s.jar" % (parts[1], parts[2], "-" + parts[3] if len(parts) > 3 else "")
        libs[lib_key(lib["name"])] = os.path.join(dev, "fabric", jar)  # Fabric's copy wins, as in a launcher
    classpath = os.pathsep.join(list(libs.values()) + [os.path.join(dev, mc, "client.jar")])
    natives = os.path.join(game, ".natives")
    os.makedirs(natives, exist_ok=True)
    subs = {
        "natives_directory": natives, "launcher_name": "slm-ci", "launcher_version": "1",
        "classpath": classpath, "classpath_separator": os.pathsep, "library_directory": os.path.join(dev, mc, "libs"),
        "auth_player_name": "SLMTest", "version_name": profile["id"], "game_directory": game,
        "assets_root": os.path.join(dev, mc, "assets"), "assets_index_name": vj["assetIndex"]["id"],
        "auth_uuid": str(uuid.uuid4()), "auth_access_token": "0", "clientid": "0", "auth_xuid": "0",
        "user_type": "msa", "version_type": "release",
    }

    def fill(text):
        for k, v in subs.items():
            text = text.replace("${%s}" % k, v)
        return text

    def args_of(items):
        out = []
        for a in items:
            if isinstance(a, str):
                out.append(fill(a))
            elif allowed(a.get("rules")):
                out.extend(fill(v) for v in ([a["value"]] if isinstance(a["value"], str) else a["value"]))
        return out

    jvm = args_of(vj["arguments"]["jvm"]) + args_of(profile.get("arguments", {}).get("jvm", []))
    game_args = args_of(vj["arguments"]["game"]) + args_of(profile.get("arguments", {}).get("game", []))
    cmd = ["java", "-Xms1G", "-Xmx3G"] + G1_ARGS.split() + jvm + [profile["mainClass"]] + game_args \
        + ["--width", "1280", "--height", "720", "--quickPlaySingleplayer", WORLD]
    log_path = os.path.join(game, "client.out")
    start = time.time()
    with open(log_path, "w") as out:
        proc = subprocess.Popen(cmd, cwd=game, stdout=out, stderr=subprocess.STDOUT)
        try:
            code = proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
            code = "timeout"
    log("client exited with %s after %.0f s" % (code, time.time() - start))
    return code, log_path, time.time() - start


def patch_options(game):
    path = os.path.join(game, "options.txt")
    values = {}
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8").read().splitlines():
            k, sep, v = line.partition(":")
            if sep:
                values[k] = v
    # Windowed for Xvfb; everything else stays as the pack ships it.
    values.update(fullscreen="false", pauseOnLostFocus="false", onboardAccessibility="false")
    with open(path, "w", encoding="utf-8") as f:
        f.write("".join("%s:%s\n" % kv for kv in values.items()))


def summarize(out, code, log_path, seconds, idx):
    os.makedirs(out, exist_ok=True)
    text = open(log_path, encoding="utf-8", errors="replace").read()
    shutil.copyfile(log_path, os.path.join(out, "client.log"))
    harness = [l for l in text.splitlines() if "[SLM-HARNESS]" in l]
    noise = [l for l in text.splitlines() if NOISE.search(l) and "[SLM-HARNESS]" not in l]
    loaded = next((l for l in text.splitlines() if "Loading " in l and " mods" in l), "")
    passed = code == 0 and any("finished" in l for l in harness) and not any("ERROR" in l for l in harness)
    metrics = {}
    for l in harness:
        m = re.search(r"metric (\w+) ([\d.]+)", l)
        if m:
            metrics[m.group(1)] = float(m.group(2))
    with open(os.path.join(out, "metrics.json"), "w", encoding="utf-8") as f:
        json.dump({"pack": idx["versionId"], "passed": passed, "metrics": metrics}, f, indent=2)
    lines = [
        "# Client run: %s" % idx["versionId"],
        "",
        "**%s** — exit %s after %.0f s" % ("PASS" if passed else "FAIL", code, seconds),
        "",
        "Software rendering under Xvfb (Mesa llvmpipe): this proves the pack starts and loads a world,",
        "and shows the screens. Its frame rate is not a benchmark.",
        "",
        "```",
        loaded.strip(),
        "```",
        "",
        "## Metrics",
        "",
        "| metric | value |",
        "| --- | --- |",
    ] + ["| %s | %.2f |" % kv for kv in sorted(metrics.items())] + [
        "",
        "## Harness",
        "",
        "```",
    ] + harness + ["```", "", "## Errors and warnings worth reading (%d)" % len(noise), "", "```"] + noise[:150] + ["```", ""]
    with open(os.path.join(out, "summary.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return passed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pack")
    ap.add_argument("--dev", required=True)
    ap.add_argument("--game", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--mc", default="26.3")
    ap.add_argument("--timeout", type=int, default=1200)
    args = ap.parse_args()
    dev, game, out = map(os.path.abspath, (args.dev, args.game, args.out))
    shutil.rmtree(game, ignore_errors=True)
    os.makedirs(os.path.join(game, "mods"))

    idx = install_pack(args.pack, game, os.path.join(os.path.dirname(game), "mod-cache"))
    build_harness(dev, args.mc, game)
    patch_options(game)
    generate_world(dev, args.mc, game, os.path.dirname(game))
    code, log_path, seconds = launch(dev, args.mc, game, args.timeout)

    shots = sorted(glob.glob(os.path.join(game, "screenshots", "*.png")))
    os.makedirs(out, exist_ok=True)
    for old in glob.glob(os.path.join(out, "*.png")):
        os.remove(old)
    for s in shots:
        shutil.copyfile(s, os.path.join(out, os.path.basename(s)))
    passed = summarize(out, code, log_path, seconds, idx)
    log("%s, %d screenshots, results in %s" % ("PASS" if passed else "FAIL", len(shots), out))
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
